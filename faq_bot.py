import os
import sys

# Текст, который будет записан в faq.txt при первом запуске.
# Формат: Ключи (для поиска), В (Вопрос), О (Ответ).
FAQ_CONTENT = """Ключи: врем, начал, конец, когда, дедлайн, скольк
В: Во сколько начало репетиции и когда дедлайн?
О: Репетиция начинается в 9:00, а сдача проектов до 18:00.

Ключи: команд, человек, участник, состав
В: Сколько человек должно быть в команде?
О: В команде допускается от 1 до 3 участников.

Ключи: трек, направлен, выбор, задач
В: Какие треки есть на этом хакатоне?
О: У нас много треков.

Ключи: сдач, сдавать, куда, гитхаб, github, репозитор, ссылк
В: Как происходит сдача проекта?
О: Сдача происходит через GitHub-репозиторий команды, репозиторий в гитхабе уже создан, вы должны принять приглащение.

Ключи: приз, победит, наград, выигрыш, мерч
В: Какие призы предусмотрены для победителей?
О: Победители получат мерч, сертификаты об участии и фаст-трек на стажировку."""

README_CONTENT = """# FAQ Bot (Тестовый кейс хакатона)

Простой консольный бот, который отвечает на 5 заранее известных вопросов про репетицию/хакатон.

## Как запустить
1. Убедитесь, что у вас установлен Python (версия 3.6+).
2. Откройте терминал и запустите скрипт:
   ```bash
   python hackathon_bot.py
   ```
3. При первом запуске скрипт автоматически создаст файл `faq.txt` в текущей директории.
4. Пишите вопросы в консоль! Для выхода введите `выход`, `exit` или `q`.

## Что получилось
- Бот читает базу знаний напрямую из `faq.txt`.
- Используется легковесный алгоритм поиска по пересечению ключевых слов (без нейросетей, RAG и сторонних библиотек).
- Бот динамически обрабатывает `faq.txt`, так что ключи и вопросы можно легко менять прямо в текстовом файле, не трогая код.
- Если бот не находит пересечений по смыслу, он честно отвечает: «Не знаю».
"""

def setup_repository_files():
    """
    Создает файлы faq.txt и README.md, если они отсутствуют в директории.
    Имитирует разворачивание репозитория команды.
    """
    if not os.path.exists('faq.txt'):
        with open('faq.txt', 'w', encoding='utf-8') as f:
            f.write(FAQ_CONTENT)
        print("[Система] Сгенерирован файл базы знаний: faq.txt")

    if not os.path.exists('README.md'):
        with open('README.md', 'w', encoding='utf-8') as f:
            f.write(README_CONTENT)
        print("[Система] Сгенерирован файл документации: README.md")

def load_faq():
    """
    Читает faq.txt и преобразует его в список словарей с ключами, вопросами и ответами.
    """
    faq_data = []
    try:
        with open('faq.txt', 'r', encoding='utf-8') as f:
            content = f.read()
        
        # Разделяем блоки по пустой строке
        blocks = content.strip().split('\n\n')
        for block in blocks:
            lines = [line.strip() for line in block.split('\n') if line.strip()]
            # Убеждаемся, что в блоке есть ключи, вопрос и ответ
            if len(lines) >= 3:
                # Извлекаем ключи, убирая префикс "Ключи:"
                keys_str = lines[0].replace('Ключи:', '').strip()
                keys = [k.strip().lower() for k in keys_str.split(',')]
                
                q = lines[1].replace('В:', '').strip()
                a = '\n'.join(lines[2:]).replace('О:', '').strip()
                
                faq_data.append({'keys': keys, 'q': q, 'a': a})
        return faq_data
    except Exception as e:
        print(f"[Ошибка] Не удалось прочитать faq.txt: {e}")
        sys.exit(1)

def find_best_answer(user_query, faq_data):
    """
    Находит лучший ответ на основе пересечения ключевых слов (корней) в запросе пользователя.
    """
    query_lower = user_query.lower()
    
    max_score = 0
    best_answer = None

    # Проходим по всем вопросам из базы
    for item in faq_data:
        # Считаем, сколько ключевых корней из этого вопроса есть в запросе пользователя
        score = sum(1 for key in item['keys'] if key in query_lower)
        
        # Обновляем лучший ответ, если совпадений больше
        if score > max_score:
            max_score = score
            best_answer = item['a']

    # Если нашли хотя бы одно совпадение по корням слов
    if max_score > 0:
        return best_answer
    else:
        return "Не знаю. Попробуйте переформулировать вопрос (например, спросите про время, команду, трек, сдачу или призы)."

def main():
    print("Инициализация репозитория...")
    setup_repository_files()
    
    faq_data = load_faq()
    if not faq_data:
        print("[Ошибка] База данных FAQ пуста. Проверьте формат faq.txt.")
        return

    print("\n" + "="*55)
    print("🤖 Терминальный бот запущен!")
    print("Напишите 'выход', 'exit' или 'q' для завершения работы.")
    print("Можете спросить меня про: время, команду, треки, сдачу и призы.")
    print("="*55 + "\n")

    # Основной цикл чата
    while True:
        try:
            user_input = input("Вы: ")
            
            # Проверка на выход
            if user_input.lower() in ['выход', 'exit', 'quit', 'q']:
                print("Бот: Удачи на репетиции хакатона! До связи!")
                break
            
            # Пропуск пустых строк
            if not user_input.strip():
                continue

            # Поиск и вывод ответа
            answer = find_best_answer(user_input, faq_data)
            print(f"Бот: {answer}\n")
            
        # Обработка внезапного прерывания (Ctrl+C или Ctrl+D)
        except (KeyboardInterrupt, EOFError):
            print("\nБот: Сеанс прерван. До связи!")
            break

# Точка входа в скрипт
if __name__ == '__main__':
    main()